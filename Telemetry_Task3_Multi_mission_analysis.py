# ## 6. Outlier Detection
#
# Rare events are detected on detrended PCA scores using a standard-deviation threshold. This helps focus on unusual short-term behavior rather than long-term drift.

# %% [code] cell 31
def outliers_sigma(df, col, k):
    """Detect rare events after detrending a selected PCA score."""
    ts = df[col].values
    ts_detrended = scipy_detrend(ts)
    ts_detrended = pd.Series(ts_detrended, index=df.index)
    
    mean = ts_detrended.mean()
    std = ts_detrended.std()
    
    lower = mean - k * std
    upper = mean + k * std

    df_out = ts_detrended[(ts_detrended < lower) | (ts_detrended > upper)]
    
    return df_out


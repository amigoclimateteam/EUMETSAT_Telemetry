def plt_STL_double(
    ts1,
    ts2,
    combo,
    detrend,
    mission_name1="Sentinel-3A",
    mission_name2="Sentinel-3B",
    remove_annual=False,
    component="residuals",
    out_path=out_path
):
    """Run STL decomposition for two missions and plot one selected component."""

    if detrend:
        d = "detrended"
    else:
        d = ""

    if remove_annual:
        ts1 = remove_annual_semiannual_cycles(ts1)
        ts2 = remove_annual_semiannual_cycles(ts2)
        ra = "removed_annual_semiannual"
    else:
        ra = ""

    def compute_stl_component(ts, component):

        ts = ts.copy()
        ts.index = pd.to_datetime(ts.index)

        q01, q99 = ts.quantile([0.01, 0.99])
        ts_clean = ts.clip(lower=q01, upper=q99)

        period = 288   # 5 minutes -> 288 samples/day
        stl = STL(ts_clean, period=period, robust=True)
        res = stl.fit()

        component = component.lower()

        if component in ["trend", "low_frequency"]:
            y = res.trend
            label = "Trend / low-frequency component"

        elif component in ["seasonality", "seasonal", "daily_seasonality"]:
            y = res.seasonal
            label = "Daily seasonality"

        elif component in ["residuals", "residual", "resid"]:
            y = res.resid
            label = "Residuals"

        else:
            raise ValueError(
                "component must be one of: 'trend', 'seasonality', or 'residuals'"
            )

        return y, label, res

    def get_outlier_values(y, outliers):

        if outliers is None:
            return None

        outlier_index = pd.to_datetime(outliers.index)
        outlier_index = outlier_index.intersection(y.index)

        if len(outlier_index) == 0:
            return None

        return y.loc[outlier_index]

    y1, component_label, res1 = compute_stl_component(ts1, component)
    y2, _, res2 = compute_stl_component(ts2, component)

    y1_out = get_outlier_values(y1, outliers_m1)
    y2_out = get_outlier_values(y2, outliers_m2)

    fig, axes = plt.subplots(
        2, 1,
        figsize=(14, 8),
        sharex=True,
        gridspec_kw={"hspace": 0.2}
    )

    axes[0].plot(
        y1.index.to_numpy(),
        y1.to_numpy(),
        linewidth=1,
        color="steelblue",
        label=component_label
    )

    axes[0].set_title(f"{mission_name1}", fontsize=22)
    axes[0].set_ylabel("Value",fontsize=20)
    axes[0].grid(True, alpha=0.3)
    axes[0].legend()

    axes[1].plot(
        y2.index.to_numpy(),
        y2.to_numpy(),
        linewidth=1,
        color="darkorange",
        label=component_label
    )

    axes[1].set_title(f"{mission_name2}", fontsize=22)
    axes[1].set_ylabel("Value",fontsize=20)
    axes[1].set_xlabel("Time",fontsize=20)
    axes[1].grid(True, alpha=0.3)
    axes[1].legend()

    if combo:
        filename = (
            f"{out_path}fft_{d}_{ra}_STL_combo_"
            f"{component}_{mission_name1}_{mission_name2}.png"
        )
    else:
        filename = (
            f"{out_path}fft_{d}_{ra}_STL_pca{pca}_"
            f"{component}_{mission_name1}_{mission_name2}.png"
        )
    plt.xticks(size=18)
    plt.yticks(size=18)
    plt.tight_layout()
    plt.savefig(filename)
    plt.show()

    return res1, res2


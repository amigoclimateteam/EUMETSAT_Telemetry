def retrieve_ts(scores, explained, combo, detrend):
    """Select one PC score or a weighted PC combination and return its sampling interval."""
    if combo == True:
        # combination between the first 3 PCAs multiplied by their relative percentages
        ts = (scores["PC1"].dropna()*explained[0] + scores["PC2"].dropna()*explained[1] +  scores["PC3"].dropna()*explained[2]).copy()
    else:
        # Select the PCA component
        ts = scores[f"PC{pca}"].dropna()
    
    ts.index = pd.to_datetime(ts.index)
    ts = ts.sort_index()
    #dt = (ts.index[1] - ts.index[0]).total_seconds()
    
    if detrend == True:
        ts_det = scipy_detrend(ts)
        ts = pd.Series(ts_det, index=ts.index)
    dt = (ts.index[1] - ts.index[0]).total_seconds()
        
    return ts, dt

def plot_power_spectrum_double(
    ts1,
    ts2,
    dt1,
    dt2,
    mission_name1,
    mission_name2,
    combo,
    detrend,
    remove_annual=False,

    out_path=out_path
):
    """Compute and compare power spectra for two mission time series."""

    if detrend:
        d = "detrended"
    else:
        d = ""

    def compute_spectrum(ts, dt, remove_annual):

        signal = ts.values
        N = len(signal)

        if remove_annual:

            signal = signal - np.mean(signal)

            window = windows.hann(len(signal))
            signal = signal * window

            yf = rfft(signal)
            xf = rfftfreq(N, d=dt)

            ra = "removed_annual"

        else:

            yf = fft(signal - np.mean(signal))
            xf = fftfreq(N, dt)

            ra = ""

        power = np.abs(yf)**2

        # positive frequencies only
        mask = xf > 0

        freq = xf[mask]
        power = power[mask]

        # frequency -> period
        period_days = 1 / freq / 86400

        order = np.argsort(period_days)

        period_days = period_days[order]
        power = power[order]

        peaks, _ = find_peaks(
            power,
            prominence=np.max(power) * 0.05
        )

        if remove_annual:

            mask = (
                (period_days > 0.1) &
                (period_days < 100)
            )

            period_days = period_days[mask]
            power = power[mask]

            peaks, _ = find_peaks(
                power,
                prominence=np.max(power) * 0.05
            )

            n_peaks = 5

            idx = np.argsort(power[peaks])[-n_peaks:]

            peaks = peaks[idx]
        return period_days, power, peaks, ra

    # spectra
    period1, power1, peaks1, ra = compute_spectrum(
        ts1,
        dt1,
        remove_annual
    )

    period2, power2, peaks2, ra = compute_spectrum(
        ts2,
        dt2,
        remove_annual
    )

    # plotting
    fig, axes = plt.subplots(
        2,
        1,
        figsize=(10, 10),
        sharex=True
    )

    configs = [
        (
            axes[0],
            period1,
            power1,
            peaks1,
            "steelblue",
            mission_name1
        ),
        (
            axes[1],
            period2,
            power2,
            peaks2,
            "darkorange",
            mission_name2
        )
    ]

    for ax, period_days, power, peaks, color, mission in configs:

        ax.plot(
            period_days,
            power,
            linewidth=1,
            color=color
        )

        ax.scatter(
            period_days[peaks],
            power[peaks],
            color="red",
            zorder=3
        )
        
        plotted_labels = set()
        
        for p in peaks:
        
            period = period_days[p]
        
            if period < 1:
                label = f"{period * 24:.1f} h"
            else:
                label = f"{period:.1f} d"
        
            # Skip duplicate labels
            if label in plotted_labels:
                continue
        
            plotted_labels.add(label)
        
            ax.annotate(
                label,
                (period_days[p], power[p]),
                textcoords="offset points",
                xytext=(5, 5),
                fontsize=13
            )

        ax.set_xscale("log")
        ax.set_yscale("log")

        ax.set_ylabel("Power",fontsize=20)

        ax.grid(True, which="both", alpha=0.3)

    axes[1].set_xlabel("Period [days]",fontsize=20)
    plt.tick_params(axis="both", labelsize=16)
    plt.tight_layout()

    if combo:

        plt.savefig(
            f'{out_path}fft_{d}_{ra}_power_spectrum_combo_comparison.png'
        )

    else:

        plt.savefig(
            f'{out_path}fft_{d}_{ra}_power_spectrum_pca{pca}_comparison.png'
        )

    plt.show()

    return (
        power1,
        peaks1,
        period1,
        power2,
        peaks2,
        period2
    )


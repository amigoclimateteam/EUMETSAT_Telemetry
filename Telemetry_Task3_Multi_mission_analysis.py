def column_renaming(df):
    df = df.reset_index()
    old_cols = list(df.columns)
    
    real_cols = [c for c in old_cols if not c.startswith("level_")]
    
    time_col = real_cols[0]
    
    rowcount_col = real_cols[1]
    
    var_cols = real_cols[2:]
    
    new_cols = []
    
    var_idx = 0
    
    for i, col in enumerate(old_cols):
    
        if i == 0:
            new_cols.append(time_col)
    
        elif i == 1:
            new_cols.append(rowcount_col)
    
        elif i % 2 == 0:
            new_cols.append(var_cols[var_idx])
            var_idx += 1
    
        else:
            new_cols.append(f"Unnamed: {i}")
    
    df.columns = new_cols
    return df
    
"""Clean one raw telemetry table and select the requested time interval."""

def data_fixing(ds, start, end):
    # Fixing the name of the columns
    ds = column_renaming(ds)
    
    # Drop Orbits not completed
    ds    = ds.rename(columns={'Rowcount S3_TM_HKP2':'Rowcount', 'Rowcount S3_TM_HKP1':'Rowcount'})
    mean  = ds["Rowcount"].mean()
    std   = ds["Rowcount"].std()
    lower = mean - std
    upper = mean + std
    ds_orbits = ds[(ds["Rowcount"] >= lower) & (ds["Rowcount"] <= upper)]
    
    # Keep variables only
    ds_parameters = ds_orbits.loc[:, ~ds_orbits.columns.str.contains("Unnamed:")].drop(columns=["Rowcount"])
    
    # Drop NaNs before the PCA
    ds_parameters_nonan = ds_parameters.dropna()
    
    # Set time
    ds_parameters_nonan["Time (ISO8601)"] = pd.to_datetime(ds_parameters_nonan["Time (ISO8601)"])
    ds_fixed = ds_parameters_nonan.rename(columns={'Time (ISO8601)':'time'}).set_index('time')

    # Slice by time interval - available period varies according to the Mission
    ds_slice = ds_fixed.loc[f"{start}-01-01":f"{end}-12-31"]
    return ds_slice

"""Load and merge the temperature files for one selected mission."""

def product_data_opening(payload, mission, start, end, input_path=input_path):
    
    # Opening the data in your folder
    data0 = pd.read_csv(f'{input_path}temperature_{payload}_{mission}.csv')
    data1 = pd.read_csv(f'{input_path}temperature_{payload}_{mission}_1.csv')

    # Apply preprocessing on the single file
    data0_fixed = data_fixing(data0, start, end)
    data1_fixed = data_fixing(data1, start, end)

    # Merge the multiple files in a single one
    df_merged = pd.concat([data0_fixed, 
                           data1_fixed,
                          ], axis=1)
    df_final = pd.concat([df_merged, data0_fixed], axis=1, join="inner")

    # Exclude columns with a constant value for each time step
    df_final_tokeep = df_final.loc[:, df_final.nunique() > 1]
    
    # Check on time coordinate
    df = df_final_tokeep.copy()
    if "time" in df.columns:
        df["time"] = pd.to_datetime(df["time"], errors="coerce")
        df = df.set_index("time")
        
    # Check on duplicated columns
    df = df.loc[:,~df.columns.duplicated()].copy()
    
    # Check on available sensors
    if len(df.columns == 40):
        print('Temperature sensors for OLCI should be 40: ok')
    else:
        print('Check number of sensors')
    return df



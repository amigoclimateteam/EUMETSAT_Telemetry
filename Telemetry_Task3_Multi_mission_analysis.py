# ### 10.4 Remove Annual and Semi-annual Cycles
#
# This helper removes annual and semi-annual harmonic components through a least-squares fit before recomputing the spectrum.

# %% [code] cell 62
def remove_annual_semiannual_cycles(ts):
    """
    Removes annual and semi-annual harmonic components from a time series.
    Assumes ts has a datetime index.
    """

    ts = ts.copy()
    ts.index = pd.to_datetime(ts.index)

    mask = ts.notna()
    y = ts.loc[mask].to_numpy()

    # Time in days from start
    t = (ts.loc[mask].index - ts.loc[mask].index[0]).total_seconds() / 86400

    annual_period = 365.25
    semiannual_period = 365.25 / 2

    X = np.column_stack([
        np.ones(len(t)),
        np.sin(2 * np.pi * t / annual_period),
        np.cos(2 * np.pi * t / annual_period),
        np.sin(2 * np.pi * t / semiannual_period),
        np.cos(2 * np.pi * t / semiannual_period),
    ])

    beta, _, _, _ = np.linalg.lstsq(X, y, rcond=None)

    fitted_cycle = X @ beta

    ts_removed = ts.copy()
    ts_removed.loc[mask] = y - fitted_cycle

    return ts_removed


def plt_STL(
    ts,
    combo,
    detrend,
    remove_annual=False,
    component="residuals",
    out_path=out_path
):
    """Run STL and plot one selected decomposition component."""
    color = "steelblue"

    if detrend:
        d = "detrended"
    else:
        d = ""

    if remove_annual:
        ts = remove_annual_semiannual_cycles(ts)
        ra = "removed_annual_semiannual"
    else:
        ra = ""

    # Remove extremes only for plotting/decomposition stability
    q01, q99 = ts.quantile([0.01, 0.99])
    ts_clean = ts.clip(lower=q01, upper=q99)

    # STL decomposition
    period = 288   # 5 minutes -> 288 samples/day
    stl = STL(ts_clean, period=period, robust=True)
    res = stl.fit()

    component = component.lower()

    if component in ["trend", "low_frequency"]:
        y = res.trend
        component_label = "Trend / low-frequency component"

    elif component in ["seasonality", "seasonal", "daily_seasonality"]:
        y = res.seasonal
        component_label = "Daily seasonality"

    elif component in ["residuals", "residual", "resid"]:
        y = res.resid
        component_label = "Residuals"

    else:
        raise ValueError(
            "component must be one of: 'trend', 'seasonality', or 'residuals'"
        )

    plt.figure(figsize=(14, 5))

    plt.plot(
        y.index.to_numpy(),
        y.to_numpy(),
        linewidth=1,
        color=color
    )

    plt.axhline(0, color="black", linewidth=0.8)

    plt.title(component_label, fontsize=25)
    plt.xlabel("Time", fontsize=20)
    plt.ylabel("Value", fontsize=20)
    plt.xticks(size=18)
    plt.yticks(size=18)
    plt.grid(True, alpha=0.3)

    if combo:
        filename = f"{out_path}fft_{d}_{ra}_STL_combo_{component}.png"
    else:
        filename = f"{out_path}fft_{d}_{ra}_STL_pca{pca}_{component}.png"

    plt.tight_layout()
    plt.savefig(filename)

    plt.show()
    return res



def ts_creation(ts, detrend=False):
    """Prepare a regular time series and return its sampling interval in seconds."""
    ts.index = pd.to_datetime(ts.index)
    ts = ts.sort_index()
    dt = (ts.index[1] - ts.index[0]).total_seconds()
    if detrend == True:
        ts_detrended = scipy_detrend(ts)
        ts = pd.Series(ts_detrended, index=ts.index)
        dt = (ts.index[1] - ts.index[0]).total_seconds()
    return ts, dt

def plot_power_spectrum(ts, dt, combo, detrend,
                        remove_annual=False,
                        out_path=out_path):
    """Compute and plot the power spectrum of a PCA score or score combination."""

    color = 'steelblue'

    if detrend == True:
        d = 'detrended'
    else:
        d = ''

    signal = ts.values
    N = len(signal)

    if remove_annual == True:
        signal = signal - np.mean(signal)
        window = windows.hann(len(signal))
        signal = signal * window
        N = len(signal)

        yf = rfft(signal)
        xf = rfftfreq(N, d=dt)
        ra = 'removed_annual'

    else:
        yf = fft(signal - np.mean(signal))
        xf = fftfreq(N, dt)
        ra = ''


    power = np.abs(yf)**2

    # masking positive frequencies
    mask = xf > 0
    freq = xf[mask]
    power = power[mask]

    # conversion: freq -> period
    period_days = 1 / freq / 86400
    order = np.argsort(period_days)
    period_days = period_days[order]
    power = power[order]

    # Peaks
    peaks, _ = find_peaks(power, prominence=np.max(power)*0.05)

    # Overwrite the parameters if remove_annual is set True
    if remove_annual == True:
        mask = (period_days > 0.1) & (period_days < 100)
        period_days = period_days[mask]
        power = power[mask]
        peaks, properties = find_peaks(power, prominence=np.max(power)*0.05)

        n_peaks = 3
        idx = np.argsort(power[peaks])[-n_peaks:]
        peaks = peaks[idx]



    # plot
    plt.figure(figsize=(10,5))

    plt.plot(period_days, power, linewidth=1,color=color)

    plt.scatter(period_days[peaks], power[peaks], color="red", zorder=3)

    for p in peaks:

        period = period_days[p]

        if period < 1:
            label = f"{period*24:.1f} h"
        else:
            label = f"{period:.1f} d"

        plt.annotate(
            label,
            (period_days[p], power[p]),
            textcoords="offset points",
            xytext=(5,5),
            fontsize=12
        )

    plt.xscale("log")
    plt.yscale("log")
    plt.tick_params(axis="both", labelsize=16)
    plt.xlabel("Period [days]",fontsize=20)
    plt.ylabel("Power",fontsize=20)

    #if combo == True:

    #    plt.title(f"Combination of first three PCAs' Power Spectrum {d} {ra}")

    #else:

    #    plt.title(f"PCA{pca}s' Power Spectrum {d} {ra}")

    plt.grid(True, which="both", alpha=0.3)
    plt.tight_layout()
    if combo == True:
        plt.savefig(f'{out_path}fft_{d}_{ra}_power_spectrum_combo.png')
    else:
        plt.savefig(f'{out_path}fft_{d}_{ra}_power_spectrum_pca{pca}.png')
    return power, peaks, period_days



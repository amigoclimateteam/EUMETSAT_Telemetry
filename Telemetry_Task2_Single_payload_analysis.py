def detrend_dataframe(df):
    """
    Removal of the linear trend to all the numeric columns
    """
    df_out = df.copy()
    numeric_cols = df_out.select_dtypes(include=[np.number]).columns
    df_out[numeric_cols] = df_out[numeric_cols].apply(
        lambda x: detrend(x.values),
        axis=0,
        result_type='expand'
    )

    return df_out



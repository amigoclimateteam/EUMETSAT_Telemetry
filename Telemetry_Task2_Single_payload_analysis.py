# ## 4. Principal Component Analysis
# 
# The PCA is run on numerical columns only. Variables are standardized before decomposition so that the PCs describe relative variability rather than raw-unit magnitude.
# 

# ### 4.1 PCA Function
# 
# The function returns:
# 
# - `explained`: variance explained by each principal component;
# - `loadings`: contribution of each original variable to each PC;
# - `scores`: time series of the projected observations in PCA space.
# 

# In[6]:


def pca_execution(df, n_components, mission_name):
    X_df = df.select_dtypes(include=[np.number])
    X_df = X_df.dropna(axis=0, how="any")
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_df.values)

    pca = PCA(n_components=n_components, random_state=0)
    X_pca = pca.fit_transform(X_scaled)
    explained = pca.explained_variance_ratio_

    print(f"OLCI | Mission {mission_name} - Variances explained per component:", explained)
    print(f"OLCI | Mission {mission_name} - Cumulated variances:",               np.cumsum(explained))

    loadings = pd.DataFrame(
        pca.components_.T,
        index=X_df.columns,
        columns=[f"PC{i+1}" for i in range(n_components)])

    scores = pd.DataFrame(
        X_pca,
        index=X_df.index,
        columns=[f"PC{i+1}" for i in range(n_components)])
    return explained, loadings, scores


